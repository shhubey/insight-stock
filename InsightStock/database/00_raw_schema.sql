-- Run first in your own Supabase project. Import data/product_snapshots.csv next.
-- Blank CSV returned_in_30d_window must remain SQL NULL.
begin;
create table if not exists public.product_snapshots_raw (
    id bigint generated by default as identity primary key,
    record_id text,
    sku text,
    product text,
    variant text,
    return_sku text,
    sold_eligible_90d integer,
    returned_in_30d_window integer,
    negative_review_mentions integer,
    main_reason text,
    stock_on_hand integer,
    total_reviews integer,
    cohort_start_date date,
    cohort_end_date date,
    snapshot_date date,
    review_start_date date,
    review_end_date date,
    return_window_days integer,
    review_excerpt_1 text,
    review_excerpt_2 text,
    source text
);
alter table public.product_snapshots_raw enable row level security;
revoke all on public.product_snapshots_raw from public, anon, authenticated;
commit;
-- IF NOT EXISTS does not upgrade an incompatible existing table.
-- Counts remain nullable so data-quality problems can be reviewed explicitly.
